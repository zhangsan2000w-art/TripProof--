  await expect(page.locator('.overview-stops')).toContainText('10');
  expect(await page.locator('.source-card:visible').count()).toBe(0);
  expect(await page.locator('.evidence-audit[open]').count()).toBe(0);
  expect(await page.locator('.report-appendix[open]').count()).toBe(0);
