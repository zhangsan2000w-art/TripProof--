  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `${folder}/report-mobile.png` });
  await tower.screenshot({ path: `${folder}/leifeng-mobile.png` });
  await tower.getByRole('button', { name: '展开雷峰塔的详情', exact: true }).click();
  await tower.locator('.evidence-audit>summary').click();
