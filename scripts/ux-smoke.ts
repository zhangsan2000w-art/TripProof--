  await expect(page.getByRole('heading', { name: '先看变化，再应用', exact: true })).toBeHidden();
  state = await (await page.request.get(`${base}/api/trips/${trip.id}`)).json() as TripState;
  expect(state.trip.items[0].start).toBe('16:30'); expect(state.run?.used).toBe(0);
  expect(state.result?.judgments.find(j => j.type === 'hours_fit')?.verdict).toBe('confirmed');
